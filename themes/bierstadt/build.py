#!/usr/bin/env python3
"""Build the generated parts of the Bierstadt themes from _palette.css.

  gtk-3.0/_base.css   GTK's own Adwaita CSS, recoloured onto the palette, with
                      gradients removed. Bierstadt uses Adwaita, bierstadt-dark
                      uses Adwaita-dark. _widgets.css is layered on top.

Run after changing gtk-3.0/_palette.css:

    python3 -I ~/.themes/bierstadt/build.py && python3 -I ~/.themes/bierstadt/xfwm4-build.py
"""
import colorsys
import os
import re

import gi
gi.require_version("Gtk", "3.0")
from gi.repository import Gio, Gtk  # noqa: E402,F401  (Gtk registers its resources)

HERE = os.path.dirname(os.path.abspath(__file__))
THEMES = os.path.dirname(HERE)
ADWAITA = "/org/gtk/libgtk/theme/Adwaita"


def palette():
    css = open(os.path.join(HERE, "gtk-3.0", "_palette.css"), encoding="utf-8").read()
    return {k: v.upper() for k, v in re.findall(r"@define-color\s+(\w+)\s+(#[0-9A-Fa-f]{6})", css)}


P = palette()


def rgb(h):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexc(t):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(x))) for x in t)


def mix(a, b, t):
    return hexc(x + (y - x) * t for x, y in zip(rgb(a), rgb(b)))


def ramp(stops, t):
    """Piecewise-linear colour ramp; stops is [(position, colour), ...]."""
    for (p0, c0), (p1, c1) in zip(stops, stops[1:]):
        if t <= p1:
            return mix(c0, c1, 0 if p1 == p0 else (t - p0) / (p1 - p0))
    return stops[-1][1]


VARIANTS = {
    # No colour accent: blues, reds, greens and oranges all fold into ink.
    "bierstadt": dict(
        source="gtk-contained.css",
        neutral=[(0.0, P["ink"]), (1.0, P["paper"])],
        accent=P["ink"],
        red=P["ink"], green=P["ink"], orange=P["ink"],
    ),
    # gwern.net's dark greys; accents fold into the inverted selection grey.
    "bierstadt-dark": dict(
        source="gtk-contained-dark.css",
        neutral=[(0.0, "#100D0A"), (0.10, P["night"]), (0.18, P["night_panel"]),
                 (0.30, P["night_hover"]), (1.0, P["night_text"])],
        accent=P["night_sel"],
        red=P["night_text"], green=P["night_text"], orange=P["night_text"],
    ),
}


def recolour(h, v):
    r, g, b = (x / 255 for x in rgb(h))
    hue, light, sat = colorsys.rgb_to_hls(r, g, b)
    deg = hue * 360
    if sat < 0.20 or light < 0.04:
        return ramp(v["neutral"], light)
    if 190 <= deg < 260:
        return v["accent"]
    if deg < 20 or deg >= 330:
        return v["red"]
    if deg < 60:
        return v["orange"]
    if deg < 170:
        return v["green"]
    return ramp(v["neutral"], light)


def strip_gradients(css):
    """background-image values that hold a gradient become `none`."""
    out, i = [], 0
    key = re.compile(r"background-image:\s*")
    while True:
        m = key.search(css, i)
        if not m:
            out.append(css[i:])
            return "".join(out)
        start = m.end()
        depth, j = 0, start
        while j < len(css):
            c = css[j]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            elif c in ";}" and depth == 0:
                break
            j += 1
        value = css[start:j]
        out.append(css[i:start])
        out.append("none" if "gradient" in value else value)
        i = j


def build(name, v):
    data = Gio.resources_lookup_data(f"{ADWAITA}/{v['source']}", 0).get_data().decode()
    css = re.sub(r"#[0-9A-Fa-f]{6}\b|#[0-9A-Fa-f]{3}\b", lambda m: recolour(m.group(0), v), data)

    def rgba(m):
        r, g, b, a = m.groups()
        return "alpha(%s, %s)" % (recolour(hexc((int(r), int(g), int(b))), v), a)

    css = re.sub(r"rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)", rgba, css)
    css = strip_gradients(css)
    # shorthand `background: <colour> linear-gradient(...)` keeps only the colour
    css = re.sub(r"(background:\s*#[0-9a-fA-F]{6})\s+linear-gradient\([^;{}]*\)(?=;)", r"\1", css)
    css = css.replace('url("assets/', f'url("resource://{ADWAITA}/assets/')
    header = (f"/* Generated by ~/.themes/bierstadt/build.py from GTK's {v['source']}.\n"
              " * Do not edit; change _palette.css or _widgets.css and rebuild. */\n\n")
    path = os.path.join(THEMES, name, "gtk-3.0", "_base.css")
    with open(path, "w", encoding="utf-8") as f:
        f.write(header + css)
    print("built", path)


if __name__ == "__main__":
    for n, v in VARIANTS.items():
        build(n, v)
